//! Downscaled JPEG thumbnails of beatmap backgrounds, cached on disk.
//!
//! osu! backgrounds are full-size images (often 1920×1080, sometimes 4K PNGs). Decoding thousands
//! of those in the webview to show 300px cards is what makes library grids stutter, so the grid
//! only ever sees small JPEGs generated once here.

use std::path::{Path, PathBuf};
use std::sync::{Condvar, Mutex};

use image::codecs::jpeg::JpegEncoder;
use image::ImageReader;

use crate::error::{Error, Result};

/// Allowed widths. Requests snap up to the next size, so the cache stays bounded.
const WIDTHS: [u32; 4] = [160, 360, 640, 1280];

pub fn snap_width(requested: u32) -> u32 {
    WIDTHS.iter().copied().find(|w| *w >= requested).unwrap_or(WIDTHS[WIDTHS.len() - 1])
}

/// Bounds parallel decodes: a scrolled grid fires dozens of requests at once and each decode of
/// a large PNG can take ~100 MB of RAM transiently.
struct Gate {
    busy: Mutex<usize>,
    cv: Condvar,
}

static GATE: Gate = Gate { busy: Mutex::new(0), cv: Condvar::new() };

fn max_parallel() -> usize {
    std::thread::available_parallelism().map(|n| n.get().saturating_sub(1).clamp(2, 6)).unwrap_or(3)
}

struct Permit;

impl Permit {
    fn acquire() -> Permit {
        let mut busy = GATE.busy.lock().unwrap_or_else(|e| e.into_inner());
        while *busy >= max_parallel() {
            busy = GATE.cv.wait(busy).unwrap_or_else(|e| e.into_inner());
        }
        *busy += 1;
        Permit
    }
}

impl Drop for Permit {
    fn drop(&mut self) {
        let mut busy = GATE.busy.lock().unwrap_or_else(|e| e.into_inner());
        *busy -= 1;
        GATE.cv.notify_one();
    }
}

/// Returns the cached thumbnail for `hash` at `width`, creating it from `source` if needed.
pub fn get_or_create(cache_dir: &Path, source: &Path, hash: &str, width: u32) -> Result<PathBuf> {
    let width = snap_width(width);
    let out = cache_dir.join(format!("{}", width)).join(&hash[..2]).join(format!("{hash}.jpg"));
    if out.is_file() {
        return Ok(out);
    }

    let _permit = Permit::acquire();
    if out.is_file() {
        return Ok(out); // generated by a concurrent request while we waited
    }

    let img = ImageReader::open(source)?
        .with_guessed_format()?
        .decode()
        .map_err(|e| Error::known("image", e.to_string()))?;

    let img = if img.width() > width {
        let height = ((img.height() as f64) * (width as f64) / (img.width() as f64)).round().max(1.0) as u32;
        img.resize_exact(width, height, image::imageops::FilterType::Triangle)
    } else {
        img
    };
    let rgb = img.to_rgb8();

    if let Some(dir) = out.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let tmp = out.with_extension(format!("{}.tmp", std::process::id()));
    {
        let file = std::fs::File::create(&tmp)?;
        let mut writer = std::io::BufWriter::new(file);
        JpegEncoder::new_with_quality(&mut writer, 84)
            .encode_image(&rgb)
            .map_err(|e| Error::known("image", e.to_string()))?;
    }
    std::fs::rename(&tmp, &out)?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn widths_snap_up() {
        assert_eq!(snap_width(1), 160);
        assert_eq!(snap_width(160), 160);
        assert_eq!(snap_width(161), 360);
        assert_eq!(snap_width(5000), 1280);
    }
}

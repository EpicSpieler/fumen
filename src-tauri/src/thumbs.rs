//! Downscaled JPEG thumbnails of beatmap backgrounds, cached on disk.
//!
//! osu! backgrounds are full-size images (often 1920×1080, sometimes 4K PNGs). Decoding thousands
//! of those in the webview to show 300px cards is what makes library grids stutter, so the grid
//! only ever sees small JPEGs generated once here.

use std::path::{Path, PathBuf};
use std::sync::{Condvar, Mutex};

use image::codecs::jpeg::JpegEncoder;
use image::ImageReader;

use crate::error::{Error, Result};

/// Allowed widths. Requests snap up to the next size, so the cache stays bounded.
const WIDTHS: [u32; 4] = [160, 360, 640, 1280];

pub fn snap_width(requested: u32) -> u32 {
    WIDTHS.iter().copied().find(|w| *w >= requested).unwrap_or(WIDTHS[WIDTHS.len() - 1])
}

/// Bounds parallel decodes: a scrolled grid fires dozens of requests at once and each decode of
/// a large PNG can take ~100 MB of RAM transiently, and decoding on every core starves the
/// webview, which then scrolls in jerks (parts of a card falling behind the rest).
///
/// Waiting requests go newest first: the cards on screen now come before the ones scrolled
/// past, and when more wait than a screenful, the oldest give up (the card asks again if it's
/// still there). Without this a fast scroll through the library queued hundreds of decodes for
/// cards long gone, and the lag grew the further you scrolled.
struct Gate {
    state: Mutex<Waiting>,
    cv: Condvar,
}

struct Waiting {
    busy: usize,
    /// tickets of the requests waiting, oldest first
    queue: Vec<u64>,
    next: u64,
}

static GATE: Gate = Gate { state: Mutex::new(Waiting { busy: 0, queue: Vec::new(), next: 0 }), cv: Condvar::new() };

/// requests waiting beyond this many, oldest first, give up
const MAX_WAITING: usize = 48;

fn max_parallel() -> usize {
    // half the cores at most: the rest are the webview's
    std::thread::available_parallelism().map(|n| (n.get() / 2).clamp(1, 4)).unwrap_or(2)
}

struct Permit;

impl Permit {
    /// A slot to decode in, or None when this request was dropped for newer ones.
    fn acquire() -> Option<Permit> {
        let mut st = GATE.state.lock().unwrap_or_else(|e| e.into_inner());
        let ticket = st.next;
        st.next += 1;
        st.queue.push(ticket);
        if st.queue.len() > MAX_WAITING {
            let drop = st.queue.len() - MAX_WAITING;
            st.queue.drain(..drop);
            GATE.cv.notify_all();
        }
        loop {
            if !st.queue.contains(&ticket) {
                return None;
            }
            if st.busy < max_parallel() && st.queue.last() == Some(&ticket) {
                st.queue.pop();
                st.busy += 1;
                return Some(Permit);
            }
            st = GATE.cv.wait(st).unwrap_or_else(|e| e.into_inner());
        }
    }
}

impl Drop for Permit {
    fn drop(&mut self) {
        let mut st = GATE.state.lock().unwrap_or_else(|e| e.into_inner());
        st.busy -= 1;
        // the newest waiting one goes next
        GATE.cv.notify_all();
    }
}

/// Returns the cached thumbnail for `hash` at `width`, creating it from `source` if needed.
pub fn get_or_create(cache_dir: &Path, source: &Path, hash: &str, width: u32) -> Result<PathBuf> {
    let width = snap_width(width);
    let out = cache_dir.join(format!("{}", width)).join(&hash[..2]).join(format!("{hash}.jpg"));
    if out.is_file() {
        return Ok(out);
    }

    let _permit = Permit::acquire().ok_or_else(|| Error::known("busy", "Dropped for newer thumbnails"))?;
    if out.is_file() {
        return Ok(out); // generated by a concurrent request while we waited
    }

    let img = ImageReader::open(source)?
        .with_guessed_format()?
        .decode()
        .map_err(|e| Error::known("image", e.to_string()))?;

    let img = if img.width() > width {
        let height = ((img.height() as f64) * (width as f64) / (img.width() as f64)).round().max(1.0) as u32;
        img.resize_exact(width, height, image::imageops::FilterType::Triangle)
    } else {
        img
    };
    let rgb = img.to_rgb8();

    if let Some(dir) = out.parent() {
        std::fs::create_dir_all(dir)?;
    }
    let tmp = out.with_extension(format!("{}.tmp", std::process::id()));
    {
        let file = std::fs::File::create(&tmp)?;
        let mut writer = std::io::BufWriter::new(file);
        JpegEncoder::new_with_quality(&mut writer, 84)
            .encode_image(&rgb)
            .map_err(|e| Error::known("image", e.to_string()))?;
    }
    std::fs::rename(&tmp, &out)?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn widths_snap_up() {
        assert_eq!(snap_width(1), 160);
        assert_eq!(snap_width(160), 160);
        assert_eq!(snap_width(161), 360);
        assert_eq!(snap_width(5000), 1280);
    }
}
